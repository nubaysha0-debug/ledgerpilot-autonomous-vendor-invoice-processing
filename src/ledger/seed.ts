const vendorById = (id: string): Vendor => {
  const vendor = vendors.find((item) => item.id === id);
  if (!vendor) throw new Error(`Unknown vendor ${id}`);
  return vendor;
};

const invoiceById = (id: string): Invoice => {
  const invoice = invoices.find((item) => item.id === id);
  if (!invoice) throw new Error(`Unknown invoice ${id}`);
  return invoice;
};

const fingerprint = (invoiceId: string): string => {
  const invoice = invoiceById(invoiceId);
  return fingerprintFor(invoice, vendorById(invoice.vendorId));
};

