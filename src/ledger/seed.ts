const line = (
  id: string,
  description: string,
  hsn: string,
  qty: number,
  unit: string,
  rateRupees: number,
): InvoiceLine => {
  const ratePaise = toPaise(rateRupees);
  return {
    id,
    description,
    hsn,
    qty,
    unit,
    ratePaise,
    totalPaise: Math.round(qty * ratePaise),
  };
};

interface InvoiceInput {
  id: string;
  invoiceNumber: string;
  vendorId: string;
  issueDate: string;
  receivedDate: string;
  dueDate: string;
  termsDays: number;
  poNumber?: string;
  grnNumber?: string;
  placeOfSupply?: string;
  gstType?: 'intra' | 'inter';
  gstRate?: number;
  lines: InvoiceLine[];
  source?: 'email' | 'upload' | 'manual';
  duplicateOf?: string;
  notes?: string;
  statedTotalRupees?: number;
}

function makeInvoice(input: InvoiceInput): Invoice {
  const { statedTotalRupees, ...rest } = input;
  const taxablePaise = sumPaise(input.lines.map((item) => item.totalPaise));
  const gst = computeGst(taxablePaise, input.gstType ?? 'intra', input.gstRate ?? 18);
  return {
    ...rest,
    placeOfSupply: input.placeOfSupply ?? 'Maharashtra (27)',
    gstType: input.gstType ?? 'intra',
    gstRate: input.gstRate ?? 18,
    source: input.source ?? 'email',
    taxablePaise,
    cgstPaise: gst.cgstPaise,
    sgstPaise: gst.sgstPaise,
    igstPaise: gst.igstPaise,
    roundOffPaise: gst.roundOffPaise,
    totalPaise: gst.totalPaise,
    statedTotalPaise:
      statedTotalRupees != null ? toPaise(statedTotalRupees) : gst.totalPaise,
    version: 1,
  };
}

